export function roleFor(structureId: string, movementId: string, phaseId: string) {
  const s = STRUCTURE_BY_ID[structureId];
  const roles = s?.roles[movementId];
  if (!roles) return undefined;
  return roles[phaseId] ?? roles['*'];
}

export function searchStructures(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return STRUCTURES;
  return STRUCTURES.filter(
    (s) => s.name.toLowerCase().includes(q) || s.aliases.some((a) => a.includes(q)) || s.type.includes(q),
  );
}
